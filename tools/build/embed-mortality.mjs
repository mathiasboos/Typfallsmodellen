/**
 * Packs the death-probability grid into the bundle as base64.
 *
 * The site has to open from disk, and a browser refuses `fetch` over file://.
 * So the 239 KB grid cannot be an asset the page requests -- it has to be part
 * of the JavaScript. This turns it into a generated module; apps/web/src/deaths.ts
 * decodes it back into the Float64Array the engine wants.
 *
 * Generated rather than committed: it is derived from packages/data, and after a
 * yearly data update `npm run build` regenerates it with everything else.
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "../..");
const binary = resolve(root, "packages/data/mortality-risks.bin");
const meta = JSON.parse(readFileSync(resolve(root, "packages/data/mortality.json"), "utf8"));
const out = resolve(root, "apps/web/src/generated/mortalityRisks.ts");

const bytes = readFileSync(binary);
if (bytes.byteLength !== meta.count * 8) {
  throw new Error(
    `mortality-risks.bin is ${bytes.byteLength} bytes; mortality.json expects ${meta.count} ` +
      `float64 values (${meta.count * 8} bytes). Regenerate packages/data first.`,
  );
}

mkdirSync(dirname(out), { recursive: true });
writeFileSync(
  out,
  `// Generated by tools/build/embed-mortality.mjs. Do not edit.\n` +
    `// ${meta.count} float64 death probabilities, ${meta.firstYear}-${meta.lastYear}, ages 0-${meta.maxAge}.\n` +
    `export const MORTALITY_RISKS_BASE64 =\n  "${bytes.toString("base64")}";\n`,
);

console.log(
  `embed-mortality: ${meta.count} values -> ${out.slice(root.length + 1)} ` +
    `(${Math.round((bytes.byteLength * 4) / 3 / 1024)} kB base64)`,
);
